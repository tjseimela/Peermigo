'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=file=>fs.readFileSync(path.join(root,file),'utf8');
const user={id:'me',full_name:'Student Example',institution_type:'university',institution:'Vaal University of Technology',campus:'Vanderbijlpark',course:'Diploma in Information Technology',modules:['Web Development 3.2','Software Engineering','Database Systems','Computer Networks'],study_method:'hybrid',availability:'evenings'};
const peer={...user,id:'peer',full_name:'Nduvho Mudau',modules:['Web Development 3.2','Database Systems','Computer Networks','Java Programming']};
let generatedMarkup='';
const rootElement={innerHTML:'',addEventListener(){},querySelector(){return {focus(){}}},remove(){},isConnected:true};
const context={console,window:{PM:{}},document:{activeElement:{focus(){},isConnected:true},body:{style:{overflow:''},appendChild(el){generatedMarkup=el.innerHTML}},createElement(){return rootElement},addEventListener(){},removeEventListener(){}},};
context.PM=context.window.PM;
vm.createContext(context);
for(const file of ['data.js','matching.js','match-breakdown.js'])vm.runInContext(source(file),context,{filename:file});
context.window.PMMatchBreakdown.open(peer,user);
const detail=context.window.PM.matchDetails(peer,user);
assert.ok(detail.showScore);
assert.match(generatedMarkup,/Why you match/);
assert.ok(generatedMarkup.includes(`${detail.score}%`));
for(const label of ['Shared subjects / modules','Course similarity','Same institution','Campus compatibility','Preferred study format','Compatible availability'])assert.ok(generatedMarkup.includes(label));
assert.match(generatedMarkup,/web development 3[. ]2/i);
assert.ok(generatedMarkup.includes('Maximum')===false);
assert.ok(fs.readFileSync(path.join(root,'app.js'),'utf8').includes('data-match-breakdown'));
assert.ok(fs.readFileSync(path.join(root,'matches.html'),'utf8').includes('match-breakdown.js'));
const suspicious={...peer,full_name:'<script>alert(1)</script>'};
context.window.PMMatchBreakdown.close();
context.window.PMMatchBreakdown.open(suspicious,user);
assert.ok(!generatedMarkup.includes('<script>alert(1)</script>'));
assert.ok(generatedMarkup.includes('&lt;script&gt;'));
const capped={...peer,campus:'different campus',study_method:'campus'};
const onCampus={...user,study_method:'campus'};
context.window.PMMatchBreakdown.close();
context.window.PMMatchBreakdown.open(capped,onCampus);
assert.ok(generatedMarkup.includes('Why the total is limited'));
console.log(`PASS: clickable score uses real ${detail.score}% result; six factors, capped-score explanation, HTML escaping`);
