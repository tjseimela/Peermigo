'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm'), path = require('node:path');
const root = path.resolve(__dirname, '..'), context = { window: { PM: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root, 'required-match-fields.js'), 'utf8'), context);
const validate = context.window.PM.matchEssentialsValidation;
const base = { institution_type:'university',institution:'Vaal University of Technology',course:'Diploma in IT',study_method:'campus',campus:'Vanderbijlpark Campus',modules:['Web Development'] };
let count=0;
function test(name, details, expected) { const r=validate({...base,...details}); assert.equal(r?.field||null,expected,`${name}: ${r?.message}`); console.log('PASS',name); count++; }
test('Complete on-campus profile is valid',{},null);
test('Campus required on campus',{campus:''},'campus');
test('Campus not required online',{study_method:'virtual',campus:''},null);
test('Campus optional for hybrid',{study_method:'hybrid',campus:''},null);
test('School does not require campus',{institution_type:'school',institution:'Secondary School',course:'Grade 12',campus:''},null);
test('At least one module required',{modules:[]},'modules');
test('At least one substantive module required',{modules:['x']},'modules');
test('Modules may contain 10',{modules:Array.from({length:10},(_,i)=>`Module ${i}`)},null);
test('11 modules rejected',{modules:Array.from({length:11},(_,i)=>`Module ${i}`)},'modules');
test('Course cannot be blank',{course:'   '},'course');
test('School grade cannot be blank',{institution_type:'school',course:''},'course');
test('Institution cannot be blank',{institution:'  '},'institution');
test('Institution type cannot be blank',{institution_type:''},'institution_type');
test('Format cannot be blank',{study_method:''},'study_method');
test('Invalid format rejected',{study_method:'unknown'},'study_method');
assert.ok(fs.readFileSync(path.join(root,'app.js'),'utf8').includes('study_method:signupStudyMethod.value'));
assert.ok(fs.readFileSync(path.join(root,'api.js'),'utf8').includes('study_method:studentDetails.study_method'));
const signupHTML=fs.readFileSync(path.join(root,'account.html'),'utf8');
assert.ok(signupHTML.includes('Help classmates find the right study partner from day one.'));
assert.ok(signupHTML.includes('id="signupStudyMethod"'));
console.log(`${count} registration/edit validation tests passed`);
