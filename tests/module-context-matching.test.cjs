'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');const PM={};const context={window:{PM},PM,console};vm.createContext(context);
for(const f of ['data.js','matching.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),context,{filename:f});
const make=(id,course,institution,codes={})=>({id,full_name:'Student '+id,institution_type:'university',course,institution,campus:'Vanderbijlpark Campus',study_method:'hybrid',availability:'evenings',modules:['Business Analysis 3.2','Web Development 3.2'],module_codes:codes});
const a=make('A','Diploma in Information Technology','VUT');
const same=make('B','Diploma in Information Technology','VUT');
const diff=make('B','Diploma in Business Management','VUT');
const elsewhere=make('B','Diploma in Information Technology','UJ');
const full=PM.matchDetails(same,a),half=PM.matchDetails(diff,a),cross=PM.matchDetails(elsewhere,a);
assert.ok(full.parts.modules>half.parts.modules,'different courses must lower module points');
assert.ok(full.parts.modules>cross.parts.modules,'other institution limits evidence');
assert.equal(half.moduleMatches[0].contextKind,'different-course');
assert.ok(half.moduleMatches.every(x=>x.similarity>0&&x.similarity<1));
assert.equal(PM.matchDetails(a,diff).score,half.score,'bidirectional match results');
const codesA={'business analysis 3.2':'BUS32','web development 3.2':'WDEV32'};
const both=PM.matchDetails(make('B','Diploma in Business Management','VUT',codesA),make('A','Diploma in Information Technology','VUT',codesA));
assert.equal(both.moduleMatches[0].contextKind,'shared-code');
assert.ok(both.parts.modules>half.parts.modules,'same institution + same codes increases credit');
const differentCodes=PM.matchDetails(make('B','Diploma in Business Management','VUT',{'business analysis 3.2':'BUS99','web development 3.2':'WEB99'}),make('A','Diploma in Information Technology','VUT',codesA));
assert.ok(differentCodes.parts.modules<half.parts.modules);
assert.equal(differentCodes.moduleMatches[0].contextKind,'different-code');
const noCourse=PM.matchDetails({...same,course:''},a);
assert.equal(noCourse.moduleMatches[0].contextKind,'course-unknown');
assert.ok(noCourse.parts.modules>=half.parts.modules,'missing course is not a confirmed mismatch');
const unrelated=PM.matchDetails({...same,modules:['Physics','Chemistry']},a);
assert.equal(unrelated.parts.modules,0,'shared code alone should not match unrelated names');
const api=fs.readFileSync(path.join(root,'api.js'),'utf8');
assert.ok(api.includes('module_codes:studentDetails.module_codes||{}'),'signup metadata carries codes');
assert.ok(api.includes('module_codes:p.module_codes||{}'),'edit profile stores codes');
assert.ok(api.includes('modules,module_codes,confident_modules'),'directory query includes codes');
const selector=fs.readFileSync(path.join(root,'subject-support.js'),'utf8');
assert.ok(selector.includes('Module code (optional)'));
assert.ok(selector.includes('module_codes:kept'));
console.log('PASS context-aware module evidence, code persistence, and missing-course fairness');
